# Compiles src/avl.c to WebAssembly for the page, then builds and runs the native tests.
# Uses Zig's bundled clang (install once with: python -m pip install --user ziglang).
$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot
New-Item -ItemType Directory -Force build | Out-Null

python -m ziglang cc --target=wasm32-freestanding -O2 -nostdlib "-Wl,--no-entry" "-Wl,--export-dynamic" "-Wl,--strip-all" -o build/avl.wasm src/avl.c
if ($LASTEXITCODE) { throw "wasm build failed" }

# The page embeds the module as base64, so it also works when index.html is opened straight from disk.
$b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes("$PSScriptRoot/build/avl.wasm"))
Set-Content -Encoding ascii js/avl-wasm.js "// generated by build.ps1 from src/avl.c - do not edit`nwindow.AVL_WASM = '$b64';"
Write-Host "build/avl.wasm  $((Get-Item build/avl.wasm).Length) bytes -> js/avl-wasm.js"

python -m ziglang cc -O2 -o build/test_avl.exe src/avl.c test/test_avl.c
if ($LASTEXITCODE) { throw "test build failed" }
& ./build/test_avl.exe
if ($LASTEXITCODE) { throw "tests failed" }
